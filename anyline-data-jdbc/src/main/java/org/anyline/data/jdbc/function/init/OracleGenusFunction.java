    private final String formula;   // 带参数的完整格式
    private boolean support = true;
    private List<String> params = null;
    private List<String> orders = null;


    OracleGenusFunction(META meta, String title, String formula) {
        this(meta, title, formula, true);
    }
    OracleGenusFunction(META meta, String title, String formula, boolean support) {
        this.meta = meta;
        this.title = title;
        this.formula = formula;
        this.support = support;
    }
	OracleGenusFunction(META meta, boolean support) {
		this(meta, null, null, support);
	}

    @Override
    public boolean support() {
        return support;
    }
    @Override
    public void support(boolean support) {
        this.support = support;
    }

    @Override
    public String title(){
        return title;
    }
    @Override
    public String formula() {
        return formula;
    }
    @Override
    public DatabaseType database() {
        return DatabaseType.Oracle;
    }

    @Override
    public META meta() {
        return meta;
    }

    @Override
    public List<String> params() {
        return params;
    }

    @Override
    public void params(List<String> params) {
        this.params = params;
    }

    @Override
    public List<String> orders() {
        // 如果 orders 已定义，直接返回
        if (orders != null && !orders.isEmpty()) {
            return orders;
        }
        // 否则从 formulatitle() 中提取参数顺序
        String formula = formula();
        if (formula != null && formula.contains("${")) {
            orders = SystemFunction.extractPlaceholders(formula);
        }
        return orders;
    }
