	@Override
	public List<String> orders() {
		// 如果 orders 已定义，直接返回
		if (orders != null && !orders.isEmpty()) {
			return orders;
		}
		// 否则从 formulatitle() 中提取参数顺序
		String formula = formula();
		if (formula != null && formula.contains("${")) {
			orders = SystemFunction.extractPlaceholders(formula);
		}
		return orders;
	}
